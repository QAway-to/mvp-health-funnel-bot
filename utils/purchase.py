"""Разбор почты в сообщении и выбор оффера под ступень.

Почта здесь — не поле формы, а способ связать два мира. В боте человек это
`chat_id`, в кассе — адрес почты, и больше ничего общего у них нет. Поэтому
адрес вылавливается из обычной реплики: «оплатил, вот моя почта ...» — и
человеку не приходится заполнять анкету в чате.

Проверка нарочно грубая. Задача — отличить адрес от «оплатил» и «спасибо», а
не решить, существует ли ящик: существование всё равно проверяет касса, а
строгая регулярка отбрасывает валидные адреса и оставляет человека без
доступа, за который он заплатил.
"""

import re

#: Адрес в свободном тексте. Без границ слова по краям: в живой реплике
#: адрес окружён кавычками, скобками и запятыми.
_EMAIL = re.compile(r"[^\s@<>()\[\],;:\"']+@(?:[A-Za-z0-9-]+\.)+[A-Za-z]{2,}")


def email_in(text: str) -> str:
    """Первый адрес почты в тексте или пустая строка."""
    found = _EMAIL.search(text or "")
    return found.group(0).strip().strip(".").lower() if found else ""


def offer_for(action: str, offers: dict[str, str]) -> str:
    """Идентификатор цены в кассе для ступени вида `buy_premium`."""
    return offers.get(action, "")
