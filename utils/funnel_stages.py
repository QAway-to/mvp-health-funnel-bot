"""Где бот находится в разговоре — и что от него требуется именно сейчас.

ЗАДАЧА. Модель не знает, сколько уже длится диалог. Ей велено узнавать о
человеке и задавать вопросы — и она задаёт их бесконечно: каждый ответ
кончается новым вопросом, кнопки вариантов делают ответ лёгким, и разговор
ходит по кругу. Ни одного плохого сообщения при этом нет; плохая только
сумма. Человек не спорит — он просто перестаёт отвечать.

РЕШЕНИЕ. На каждом ходу к системному промпту приклеивается одна строка: это
твой N-й ответ, сейчас делай вот это. Стандарт телеграм-воронок — 3–5
вопросов квалификации, потом оффер; здесь он же, разложенный по ходам.

Строка не накапливается в истории: старая снимается, новая ставится. Иначе
модель читала бы четыре противоречащих указания подряд и слушалась бы
последнего в лучшем случае.
"""

from pathlib import Path

PROMPTS = Path(__file__).resolve().parents[1] / "prompts"
STAGES_FILE = "funnel_stages.txt"

#: Ход после последнего описанного: дальше поведение уже не меняется.
BEYOND = "дальше"
#: Особый случай, который важнее номера хода: продавать больше нечего.
PAID = "оплачено"


def load_stages(path: Path | None = None) -> dict[str, str]:
    """Указания по ходам: `"1"` → текст, плюс `дальше` и `оплачено`."""
    source = path or (PROMPTS / STAGES_FILE)
    if not source.is_file():
        return {}

    stages: dict[str, str] = {}
    current = ""
    lines: list[str] = []

    def flush() -> None:
        if current:
            text = "\n".join(lines).strip()
            if text:
                stages[current] = text

    for raw in source.read_text(encoding="utf-8").splitlines():
        if raw.startswith("#"):
            continue
        if raw.startswith("== "):
            flush()
            current = raw[3:].strip()
            lines = []
            continue
        lines.append(raw)
    flush()
    return stages


def stage_for(stages: dict[str, str], *, message_number: int, is_premium: bool) -> str:
    """Что делать на этом ходу. Пусто — указаний нет, ведём как обычно.

    `message_number` — какой это по счёту ответ бота, считая с первого.

    Оплативший идёт по своей ветке независимо от номера: ему нечего
    продавать, а продолжать воронку после покупки — верный способ выглядеть
    так, будто платёж не заметили.
    """
    if is_premium:
        return stages.get(PAID, "")
    return stages.get(str(message_number)) or stages.get(BEYOND, "")


def offer_due(stages: dict[str, str], *, message_number: int) -> bool:
    """Тот ли это ход, на котором показывается карточка выбора уровня.

    Определяется по тексту указаний, а не отдельным числом в коде: два места,
    где записано «на четвёртом», разъедутся, и оффер будет обещан в промпте
    на одном ходу, а кнопка появится на другом.
    """
    stage = stages.get(str(message_number), "")
    return "предлагаешь доступ" in stage.lower()
