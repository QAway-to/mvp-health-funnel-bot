"""Где бот находится в разговоре — и что от него требуется именно сейчас.

ЗАДАЧА. Модель не знает, сколько уже длится диалог. Ей велено узнавать о
человеке и задавать вопросы — и она задаёт их бесконечно: каждый ответ
кончается новым вопросом, кнопки вариантов делают ответ лёгким, и разговор
ходит по кругу. Ни одного плохого сообщения при этом нет; плохая только
сумма. Человек не спорит — он просто перестаёт отвечать.

РЕШЕНИЕ. На каждом ходу к системному промпту приклеивается одна строка: это
твой N-й ответ, сейчас делай вот это. Стандарт телеграм-воронок — 3–5
вопросов квалификации, потом оффер; здесь он же, разложенный по ходам.

Строка не накапливается в истории: старая снимается, новая ставится. Иначе
модель читала бы четыре противоречащих указания подряд и слушалась бы
последнего в лучшем случае.
"""

from pathlib import Path

PROMPTS = Path(__file__).resolve().parents[1] / "prompts"
STAGES_FILE = "funnel_stages.txt"

#: Ход после последнего описанного: дальше поведение уже не меняется.
BEYOND = "дальше"
#: Особый случай, который важнее номера хода: продавать больше нечего.
PAID = "оплачено"


def load_stages(path: Path | None = None) -> dict[str, str]:
    """Указания по ходам: `"1"` → текст, плюс `дальше` и `оплачено`."""
    source = path or (PROMPTS / STAGES_FILE)
    if not source.is_file():
        return {}

    stages: dict[str, str] = {}
    current = ""
    lines: list[str] = []

    def flush() -> None:
        if current:
            text = "\n".join(lines).strip()
            if text:
                stages[current] = text

    for raw in source.read_text(encoding="utf-8").splitlines():
        if raw.startswith("#"):
            continue
        if raw.startswith("== "):
            flush()
            current = raw[3:].strip()
            lines = []
            continue
        lines.append(raw)
    flush()
    return stages


def stage_for(stages: dict[str, str], *, message_number: int, is_premium: bool) -> str:
    """Что делать на этом ходу. Пусто — указаний нет, ведём как обычно.

    `message_number` — какой это по счёту ответ бота, считая с первого.

    Оплативший идёт по своей ветке независимо от номера: ему нечего
    продавать, а продолжать воронку после покупки — верный способ выглядеть
    так, будто платёж не заметили.
    """
    if is_premium:
        return stages.get(PAID, "")
    return stages.get(str(message_number)) or stages.get(BEYOND, "")


#: По этим словам в указаниях узнаётся ход оффера.
_OFFER_MARK = "предлагаешь доступ"


def offer_turn(stages: dict[str, str]) -> int:
    """На каком ходу показывается карточка выбора уровня. 0 — такого хода нет.

    Определяется по тексту указаний, а не отдельным числом в коде: два места,
    где записано «на четвёртом», разъедутся, и оффер будет обещан в промпте
    на одном ходу, а кнопка появится на другом.
    """
    turns = [
        int(key)
        for key, text in stages.items()
        if key.isdigit() and _OFFER_MARK in text.lower()
    ]
    return min(turns) if turns else 0


def offer_due(stages: dict[str, str], *, message_number: int) -> bool:
    """Ровно ли этот ход назначен оффером — проверка самого файла указаний.

    Только для тестов и проверок: показ кнопки на равенство завязывать
    нельзя. Ход можно проскочить — ответ на нём мог упасть с ошибкой, а
    человек мог начать разговор ещё до того, как указания появились, — и
    тогда оффер не наступил бы уже никогда. Решает `should_show_cta`.
    """
    return offer_turn(stages) == message_number


def should_show_cta(
    *,
    messages: int,
    cta_shown: int,
    turn: int,
    gap: int,
    max_times: int,
    is_premium: bool,
    offer_ready: bool,
) -> bool:
    """Показывать ли карточку выбора уровня под этим ответом бота.

    Отдельной функцией, а не выражением по месту: раньше условие жило в
    bot.py, а тест держал его копию. Копия и осталась правильной, когда
    оригинал сломался, — проверялось не то, что выполняется.

    `messages` — какой это по счёту ответ бота, `cta_shown` — сколько раз
    оффер уже показан. Первый показ идёт по порогу, а не по равенству ходу:
    ход можно проскочить (ответ на нём упал с ошибкой — он всё равно
    засчитан; человек был премиумом; разговор начат до появления указаний), и
    на равенстве оффер не пришёл бы уже никогда — вторая ветка требует, чтобы
    первый показ состоялся. Повторный — через разговор, а не следующим
    сообщением: подряд это давление, а не напоминание.
    """
    if not offer_ready or is_premium or cta_shown >= max_times:
        return False
    if not cta_shown:
        return messages >= turn
    return messages >= turn + cta_shown * gap
