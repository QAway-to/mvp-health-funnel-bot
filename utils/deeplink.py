"""Разбор метки, с которой человек приходит в бота по ссылке.

`t.me/<bot>?start=<payload>` — единственный параметр, который Telegram
передаёт боту при первом входе. Раньше в нём ехало только направление
(`son`, `zakalivanie`), и этого хватало: с лендинга вела одна кнопка.

Теперь с лендинга ведут две. Кнопка «Звёздами в Telegram» стоит рядом с
конкретным уровнем подписки, и уровень надо донести до бота — иначе человек
выбирает тариф на сайте, приходит в чат и выбирает его заново. Второй выбор
того же самого читается как «меня не услышали», и до оплаты доходят не все.

Поэтому метка стала составной: `buy_base__son` — уровень и направление через
двойное подчёркивание. Разделитель именно такой, потому что дефис уже занят
внутри направлений (`vrednye-privychki`), а Telegram в payload пропускает
только буквы, цифры, дефис и подчёркивание.
"""

#: Разделитель уровня и направления. Двойной, чтобы не спутать с одинарным
#: подчёркиванием внутри самого уровня (`buy_base`).
SEPARATOR = "__"


def parse_start_payload(payload: str, known_plans: "set[str] | frozenset[str]") -> tuple[str, str]:
    """Разобрать метку на (уровень, направление).

    Уровень возвращается, только если он есть в `known_plans`: метка приходит
    из адресной строки, то есть от кого угодно, и превращать её в покупку без
    сверки со своим же списком нельзя.

    Неизвестное значение целиком уходит в направление — там оно безвредно
    (в худшем случае человек получит приветствие по умолчанию), а придумывать
    ему покупку мы не станем.
    """
    payload = (payload or "").strip()
    if not payload:
        return "", ""

    head, separator, tail = payload.partition(SEPARATOR)
    if separator and head in known_plans:
        return head, tail
    if payload in known_plans:
        return payload, ""
    return "", payload
