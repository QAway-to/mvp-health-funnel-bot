"""Варианты ответа кнопками там, где бот задал вопрос «или — или».

ЗАЧЕМ. Бот ведёт разговор вопросами: «засыпаешь быстро или чаще лежишь и не
можешь выключить голову?» Написать ответ словами — работа: надо
сформулировать, набрать, отправить. Нажать — не работа. Разница между ними и
есть разница между продолженным разговором и брошенным.

Кнопки при этом не должны придумываться отдельно от вопроса. Формулировки
каждый раз новые — их пишет модель под конкретного человека, и держать рядом
второй, зашитый в код список значило бы, что кнопки говорят одно, а текст
другое.

ДВА СПОСОБА, И ПОРЯДОК ВАЖЕН.

1. Модель сама помечает варианты строкой `@варианты: первый | второй`.
   Надёжно и однозначно; так и просим в промпте.
2. Если пометки нет — вытаскиваем из самого вопроса «A или B?». Модель
   забывает инструкции тем чаще, чем длиннее разговор, и без запасного пути
   кнопки пропадали бы именно там, где разговор уже пошёл.

Разбор нарочно осторожный: лучше не показать кнопки, чем показать неверные.
Кнопка, не совпадающая с вопросом, читается как сбой и обрывает разговор
надёжнее, чем её отсутствие.
"""

import re

from utils.telegram_html import plain_text

#: Пометка вариантов в ответе модели. Уходит из текста до отправки: человек
#: должен видеть вопрос, а не служебную строку.
MARKER = "@варианты:"

#: Предел Telegram на подпись кнопки — вернее, предел читаемости. Длинную
#: подпись Telegram обрезает многоточием, и человек не видит, что выбирает.
LABEL_LIMIT = 40

#: Больше трёх вариантов — это уже анкета, а не разговор.
MAX_OPTIONS = 3

_MARKER_LINE = re.compile(rf"^\s*{re.escape(MARKER)}\s*(.+)$", re.MULTILINE | re.IGNORECASE)

#: Вопрос в конце реплики: берём последнее предложение с «?».
_LAST_QUESTION = re.compile(r"([^.!?\n]*\?)\s*$")

#: «A или B» внутри вопроса. Пробелы вокруг обязательны: иначе разделителем
#: становится «или» внутри слова.
_OR = re.compile(r"\s+или\s+", re.IGNORECASE)


def _clean(option: str) -> str:
    """Подпись кнопки из куска фразы.

    Разметку снимаем первой: к этому месту ответ модели уже переведён в HTML,
    и в подписи кнопки теги видны как есть — «<b>Встаю на рассвете</b>».
    """
    text = plain_text(option).strip().strip("«»\"'()").strip(" ,;:—-?")
    if len(text) > LABEL_LIMIT:
        text = text[: LABEL_LIMIT - 1].rstrip() + "…"
    # С заглавной: подписи выкраиваются из разных мест фразы, и вперемешку
    # они выглядят как опечатка, а не как выбор.
    return text[:1].upper() + text[1:] if text else text


def _from_marker(text: str) -> tuple[str, tuple[str, ...]]:
    found = _MARKER_LINE.search(text)
    if not found:
        return text, ()
    options = tuple(
        _clean(part) for part in found.group(1).split("|") if _clean(part)
    )[:MAX_OPTIONS]
    # Служебную строку убираем целиком, вместе с пустой строкой перед ней.
    clean = (text[: found.start()].rstrip() + "\n" + text[found.end() :].lstrip()).strip()
    return clean, options


def _from_question(text: str) -> tuple[str, ...]:
    """Вытащить «A или B» из последнего вопроса реплики.

    Только из последнего и только если частей ровно две-три: «или» встречается
    и в перечислениях внутри объяснения, и там оно вариантами не является.
    """
    question = _LAST_QUESTION.search(text.strip())
    if not question:
        return ()
    body = question.group(1).strip().rstrip("?").strip()
    if not body:
        return ()

    parts = [part.strip() for part in _OR.split(body) if part.strip()]
    if not 2 <= len(parts) <= MAX_OPTIONS:
        return ()

    # Первый кусок несёт саму постановку вопроса («У тебя как с засыпанием —
    # засыпаешь быстро»), и целиком в кнопку он не годится. Отрезаем хвост
    # ДО укорачивания: наоборот — и подпись обрежется по постановке вопроса,
    # а сам вариант из неё исчезнет.
    for separator in ("—", "–", ":", " - "):
        if separator in parts[0]:
            parts[0] = parts[0].split(separator)[-1].strip()
            break

    options = tuple(_clean(part) for part in parts)
    return options if all(options) else ()


def extract(text: str) -> tuple[str, tuple[str, ...]]:
    """Текст без служебной строки и варианты ответа к нему.

    Пустой кортеж — вариантов нет, сообщение уходит как обычно.
    """
    clean, options = _from_marker(text)
    if options:
        return clean, options
    return clean, _from_question(clean)
