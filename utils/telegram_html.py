"""Привести ответ модели к разметке, которую Telegram действительно понимает.

Промпт запрещает markdown и требует HTML-теги. Модель это правило нарушает —
не всегда, но регулярно, потому что markdown для неё родной. Человек в чате
видит буквальные «**бег**» вместо жирного, и выглядит это как поломка.

Правилом в промпте такое не лечится: правило уже написано, и оно уже не
соблюдается. Лечится преобразованием на выходе — здесь.

Работаем только с тем, что модель реально присылает: `**жирный`**, `__`, `*`,
заголовки решётками, маркеры списка и одиночные backtick'и. HTML-теги, которые
она поставила правильно, не трогаем.
"""

import re

# Заголовки: «## Разминка» → жирная строка. Решётки Telegram не понимает вовсе,
# а строка-заголовок в ответе всё-таки смысловая.
_HEADING = re.compile(r"^[ \t]{0,3}#{1,6}[ \t]+(.+?)[ \t]*$", re.M)

# Маркер списка «* пункт» → тире. Делается до всего остального: иначе одиночная
# звёздочка списка склеится в курсив со следующей.
_BULLET = re.compile(r"^([ \t]{0,3})\*[ \t]+", re.M)

_BOLD = re.compile(r"\*\*(?=\S)(.+?)(?<=\S)\*\*", re.S)
_UNDERLINE = re.compile(r"__(?=\S)(.+?)(?<=\S)__", re.S)
# Одиночная звёздочка — курсив, но только когда она действительно обрамляет
# слово: без этих условий под замену попадали умножение и обрывки формул.
_ITALIC = re.compile(r"(?<![\w*])\*(?=\S)([^*\n]+?)(?<=\S)\*(?![\w*])")
_CODE = re.compile(r"`([^`\n]+)`")


def to_telegram_html(text: str) -> str:
    """Markdown, который просочился в ответ, → HTML-теги Telegram."""
    if not text:
        return text

    text = _HEADING.sub(r"<b>\1</b>", text)
    text = _BULLET.sub(r"\1— ", text)
    text = _BOLD.sub(r"<b>\1</b>", text)
    text = _UNDERLINE.sub(r"<b>\1</b>", text)
    text = _ITALIC.sub(r"<i>\1</i>", text)
    text = _CODE.sub(r"<code>\1</code>", text)
    return text


def has_markdown(text: str) -> bool:
    """Осталось ли в тексте то, что Telegram покажет как есть.

    Нужно не для замены, а для лога: если модель нарушает правило часто,
    это повод править промпт, а не молча чинить каждый ответ.
    """
    return bool(
        _BOLD.search(text)
        or _UNDERLINE.search(text)
        or _ITALIC.search(text)
        or _HEADING.search(text)
    )
