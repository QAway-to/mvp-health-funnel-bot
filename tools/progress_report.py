def totals() -> dict[str, object]:
    """Итоги из статусов. Руками их не пишут — именно так v3 и разошлась."""
    counts = {DONE: 0, PARTIAL: 0, NOT_STARTED: 0}
    for item in ITEMS:
        counts[item.status] += 1
    average = round(sum(item.readiness for item in ITEMS) / len(ITEMS))
    return {"counts": counts, "average": average, "total": len(ITEMS)}


def question_totals() -> dict[str, int]:
    """Сколько вопросов в каждом из четырёх ответов — тоже из строк, не руками."""
    counts = {YES: 0, MAYBE: 0, EDGE: 0, NO: 0}
    for _, _, _, now, _ in QUESTIONS:
        counts[now] += 1
    return counts


def moved_questions() -> tuple[tuple[str, str, str, str, str], ...]:
    """Вопросы, у которых ответ изменился с 18.08. Это и есть отчёт о работе."""
    return tuple(row for row in QUESTIONS if row[2] != row[3])


def build(out: Path) -> None:
    try:
        from openpyxl import Workbook
        from openpyxl.styles import Alignment, Font, PatternFill
        from openpyxl.utils import get_column_letter
    except ImportError:
        sys.exit("Нет openpyxl. Установите:\n    pip install openpyxl")

    head_font = Font(bold=True, color="FFFFFF")
    head_fill = PatternFill("solid", fgColor="2F5597")
    bold = Font(bold=True)
    title = Font(bold=True, size=12)
    wrap = Alignment(wrap_text=True, vertical="top")
    status_fill = {
        DONE: PatternFill("solid", fgColor="D6EAD6"),
        PARTIAL: PatternFill("solid", fgColor="FFF2CC"),
        NOT_STARTED: PatternFill("solid", fgColor="F8D7D7"),
    }

    book = Workbook()
    book.remove(book.active)

    def sheet(name: str, widths: tuple[int, ...]):
        page = book.create_sheet(name)
        for index, width in enumerate(widths, 1):
            page.column_dimensions[get_column_letter(index)].width = width
        return page

    def header(page, row: int, columns: tuple[str, ...]) -> int:
        for index, text in enumerate(columns, 1):
            cell = page.cell(row=row, column=index, value=text)
            cell.font = head_font
            cell.fill = head_fill
            cell.alignment = wrap
        page.freeze_panes = page.cell(row=row + 1, column=1)
        return row + 1

    def rows(page, row: int, values: tuple[tuple[str, ...], ...]) -> int:
        for line in values:
            for index, value in enumerate(line, 1):
                page.cell(row=row, column=index, value=value).alignment = wrap
            row += 1
        return row

    def block(page, row: int, caption: str, lines) -> int:
        page.cell(row=row, column=1, value=caption).font = title
        row += 1
        for line in lines:
            if isinstance(line, tuple):
                page.cell(row=row, column=1, value=line[0]).font = bold
                page.cell(row=row, column=2, value=line[1]).alignment = wrap
            else:
                page.cell(row=row, column=2, value=line).alignment = wrap
            row += 1
        return row + 1

    numbers = totals()
    counts = numbers["counts"]

    summary = sheet("Сводка", (34, 110))
    summary.cell(row=1, column=1, value="Федерация Здоровья — отчёт о ходе работ").font = Font(
        bold=True, size=14
    )
    row = 3
    row = block(summary, row, "О документе", (
        ("План", PLAN),
        ("Дата отчёта", REPORT_DATE),
        ("Версия", VERSION),
        ("Предыдущий отчёт", f"{PREVIOUS} — средняя готовность 31%"),
        ("Что охвачено", "Telegram-бот, сайт, мобильное приложение и все материалы проекта"),
    ))
    row = block(summary, row, "Итог по пунктам плана", (
        ("Готово", f"{counts[DONE]} из {numbers['total']}"),
        ("Частично", f"{counts[PARTIAL]} из {numbers['total']}"),
        ("Не начато", f"{counts[NOT_STARTED]} из {numbers['total']}"),
        ("Средняя готовность", f"{numbers['average']}%"),
    ))
    row = block(summary, row, "Что работает сегодня", WORKS_TODAY)
    row = block(summary, row, f"Что сделано с {PREVIOUS_DATE}", SINCE_PREVIOUS)
    row = block(summary, row, "Решения заказчика, меняющие план", DECISIONS)
    row = block(summary, row, "Что мешает запуску", BLOCKERS)
    block(summary, row, "Как читать таблицу", HOW_TO_READ)

    progress = sheet("Прогресс", (9, 46, 15, 12, 11, 66, 56, 15, 56))
    row = header(progress, 1, (
        "№ пункта", "Пункт плана", "Направление", "Статус", "Готовность", "Что сделано",
        "Что осталось", "Где", f"Что изменилось с {PREVIOUS_DATE}",
    ))
    for item in ITEMS:
        values = (
            item.number, item.plan, item.area, item.status, item.readiness / 100,
            item.done, item.left, item.where, item.changed,
        )
        for index, value in enumerate(values, 1):
            progress.cell(row=row, column=index, value=value).alignment = wrap
        progress.cell(row=row, column=4).fill = status_fill[item.status]
        progress.cell(row=row, column=5).number_format = "0%"
        row += 1

    questions = sheet("Вопросы аудитории", (6, 54, 13, 13, 90))
    asked = question_totals()
    row = block(questions, 1, f"Разбор {len(QUESTIONS)} вопросов — пересчёт от {REPORT_DATE}", (
        *QUESTIONS_NOTE,
        ("Отвечает уверенно", f"{asked[YES]} из {len(QUESTIONS)}"),
        ("Отвечает частично", f"{asked[MAYBE]} из {len(QUESTIONS)}"),
        ("Граница — отвечать не будем", f"{asked[EDGE]} из {len(QUESTIONS)}"),
        ("Дырки — нужен ваш текст", f"{asked[NO]} из {len(QUESTIONS)}"),
        ("Сдвинулось с 18.08", f"{len(moved_questions())} вопросов"),
    ))
    row = header(questions, row, ("№", "Вопрос", f"Было {PREVIOUS_DATE[:5]}", "Стало",
                                 "Чем закрыт или почему нет"))
    verdict_fill = {
        YES: status_fill[DONE],
        MAYBE: status_fill[PARTIAL],
        EDGE: PatternFill("solid", fgColor="E4E4E4"),
        NO: status_fill[NOT_STARTED],
    }
    for number, text, was, now, basis in QUESTIONS:
        for index, value in enumerate((number, text, was, now, basis), 1):
            questions.cell(row=row, column=index, value=value).alignment = wrap
        questions.cell(row=row, column=4).fill = verdict_fill[now]
        row += 1

    materials = sheet("Материалы", (44, 24, 16, 18, 70))
    rows(materials, header(materials, 1, MATERIALS[0]), MATERIALS[1:])

    funnels = sheet("Воронки", (5, 28, 60, 60))
    rows(funnels, header(funnels, 1, FUNNELS[0]), FUNNELS[1:])

    out.parent.mkdir(parents=True, exist_ok=True)
    book.save(out)


def main() -> None:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")

    default = (
        Path.home() / "Downloads"
        / f"Прогресс_Федерация_Здоровья_{REPORT_DATE}_{VERSION}.xlsx"
    )
    parser = argparse.ArgumentParser(description="Собрать таблицу прогресса для заказчика")
    parser.add_argument("--out", type=Path, default=default, help=f"куда писать ({default.name})")
    args = parser.parse_args()

    build(args.out.expanduser())
    numbers = totals()
    counts = numbers["counts"]
    print(args.out)
    print(
        f"Пунктов {numbers['total']}: готово {counts[DONE]}, частично {counts[PARTIAL]}, "
        f"не начато {counts[NOT_STARTED]}; средняя готовность {numbers['average']}%"
    )


if __name__ == "__main__":
    main()
