export const requisites = {
  /** Кто принимает обязательства. Единственное обязательное поле. */
  entity: 'Федерация здоровья',
  /** Регистрационный номер. Пусто — строка не печатается. */
  taxId: '',
  /** Адрес. Пусто — строка не печатается. */
  address: '',
  /** Почта для обращений. Пусто — обращения идут через бота. */
  email: '',
} as const;

/** Документ показывается, если названа сторона. Остальное — по желанию. */
export const isReady = requisites.entity.trim().length > 0;

/** Канал для обращений: почта, если есть, иначе бот — он есть всегда. */
export const contactLine = requisites.email
  ? `Электронная почта: ${requisites.email}`
  : `Telegram-бот: ${site.lead.telegramUrl.replace('https://', '')}`;

/** Строка реквизита, если он заполнен. Пустые в документ не попадают. */
const line = (label: string, value: string): string[] =>
  value.trim() ? [`${label}: ${value}`] : [];

const price = `${site.subscription.tiers.base.price}, ${site.subscription.tiers.premium.price} или ${site.subscription.tiers.pro.price} ${site.subscription.period}`;

