/**
 * Языки сайта.
 *
 * АУДИТОРИЯ — РУССКОЯЗЫЧНОЕ ПРОСТРАНСТВО, и русский остаётся основным: он
 * лежит в корне, без префикса, потому что менять адреса работающих страниц
 * ради симметрии значит потерять всё, что на них ссылается.
 *
 * Английский нужен не «для полноты». Он открывает разговор с теми, кто по-
 * русски не говорит: инструкторы холодовых практик, сообщества зимнего
 * плавания, подкасты о долголетии. Без английской страницы такое письмо
 * некуда вести.
 *
 * ЧТО ПЕРЕВЕДЕНО СЕЙЧАС: оболочка сайта, главная, вход и оба юридических
 * документа — то есть законченная точка входа. Страницы шести направлений
 * остаются русскими: там тридцать страниц прозы, и перевод наспех хуже
 * честного отсутствия. Переключатель на них ведёт на английскую главную,
 * а не в пустоту.
 */

export const LANGS = ['ru', 'en'] as const;

export type Lang = (typeof LANGS)[number];

export const DEFAULT_LANG: Lang = 'ru';

/**
 * Какие страницы существуют по-английски. Остальные ведут на главную.
 *
 * Список должен совпадать с тем, что реально собирается в `dist/en/`. Он уже
 * разошёлся один раз: сюда были вписаны страницы, которых нет, и переключатель
 * вёл на 404 — то есть ровно туда, от чего он и должен спасать. Совпадение
 * проверяется тестом, а не вниманием.
 */
export const TRANSLATED_PATHS = [
  '/',
  '/beg/',
  '/son/',
  '/zakalivanie/',
  '/vrednye-privychki/',
  '/zaryadka/',
  '/massazh/',
] as const;

/**
 * Язык по адресу страницы. `/en/...` — английский, всё остальное русское.
 */
export const langFromUrl = (url: URL): Lang =>
  url.pathname.startsWith('/en/') || url.pathname === '/en' ? 'en' : DEFAULT_LANG;

/** Тот же путь на другом языке. */
export const switchLang = (pathname: string, to: Lang): string => {
  const bare = pathname.replace(/^\/en/, '') || '/';
  if (to === DEFAULT_LANG) return bare;
  // Английской версии этой страницы может не быть — тогда ведём на главную.
  // Ссылка на несуществующий адрес хуже, чем ссылка на более общий:
  // человек нажимает «English» и попадает на 404 вместо сайта.
  const translated = (TRANSLATED_PATHS as readonly string[]).includes(bare);
  return translated ? `/en${bare === '/' ? '/' : bare}` : '/en/';
};

/** Подпись переключателя: показываем язык, на который переведём. */
export const OTHER_LANG_LABEL: Record<Lang, string> = {
  ru: 'EN',
  en: 'RU',
};
