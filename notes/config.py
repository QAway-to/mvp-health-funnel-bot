"""Настройки бота заметок. Свои, ни одна не пересекается с проектными.

Пустое значение — рабочее состояние, а не поломка: пока токена нет, маршрут
не подключается вовсе и модуль не делает ничего. Тот же принцип, что и в
остальном сервисе.
"""

from __future__ import annotations

import os

#: Токен отдельного бота от BotFather. Пусто — модуль выключен целиком.
BOT_TOKEN = os.getenv("NOTES_BOT_TOKEN", "").strip()

#: Telegram id владельца. Всё, что приходит не от него, молча игнорируется.
#:
#: Молча — намеренно. Личный бот находится поиском, и отвечать чужому «вам
#: сюда нельзя» значит подтверждать, что бот живой и чей-то. Пустой ответ
#: не сообщает ничего.
OWNER_ID = os.getenv("NOTES_OWNER_ID", "").strip()

#: Секрет вебхука. Telegram шлёт его заголовком, мы сверяем.
WEBHOOK_SECRET = os.getenv("NOTES_WEBHOOK_SECRET", "").strip()

#: Куда складывать заметки: `владелец/репозиторий`.
ARCHIVE_REPO = os.getenv("NOTES_ARCHIVE_REPO", "QAway-to/tg-notes-archive").strip()

#: Токен GitHub с правом записи содержимого — только в этот репозиторий.
GITHUB_TOKEN = os.getenv("NOTES_GITHUB_TOKEN", "").strip()

#: Модель распознавания.
#:
#: `tiny` — 75 МБ, `base` — 145 МБ, `small` — под гигабайт. На двух гигабайтах
#: сервиса `base` лежит с тройным запасом, поэтому он и стоит по умолчанию.
#: Если память когда-нибудь начнёт поджимать — это одна переменная, а не
#: переписывание кода.
WHISPER_MODEL = os.getenv("NOTES_WHISPER_MODEL", "base").strip()

#: Ширина луча декодера.
#:
#: 1 — жадный разбор, быстрый и заметно худший: слова выходят обрубленными.
#: 5 — библиотечное значение и разумный предел для одного ядра. Больше даёт
#: мало, а считает заметно дольше.
BEAM_SIZE = int(os.getenv("NOTES_BEAM_SIZE", "5"))

#: Потолок длительности записи в секундах.
#:
#: Ядро у сервиса одно, и пока считается заметка, бот Федерации отвечает
#: покупателям медленнее. Случайно пересланный часовой подкаст занял бы его
#: надолго — поэтому такое отклоняется до расшифровки, а не после.
MAX_AUDIO_SECONDS = int(os.getenv("NOTES_MAX_AUDIO_SECONDS", "900"))

#: Часовой пояс владельца в виде смещения от UTC — для ссылок в календарь.
TIMEZONE = os.getenv("NOTES_TIMEZONE", "Europe/Kyiv").strip()


def is_configured() -> bool:
    """Есть ли смысл подключать маршрут.

    Токен и секрет вебхука обязательны: без первого нечем отвечать, без
    второго вебхук принимал бы что угодно от кого угодно. Остальное
    необязательно — без токена GitHub бот просто вернёт расшифровку в чат,
    не сохраняя её.
    """
    return bool(BOT_TOKEN and WEBHOOK_SECRET)


def archive_enabled() -> bool:
    return bool(GITHUB_TOKEN and ARCHIVE_REPO)


#: Путь вебхука. Секрета в адресе нет — он приезжает заголовком, а адреса
#: попадают в логи прокси целиком.
WEBHOOK_PATH = "/notes/webhook"
